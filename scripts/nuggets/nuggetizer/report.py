"""Preview report: nuggets side by side, validation, gold self-score, tokens and extrapolated cost."""
from __future__ import annotations

import json
import random
import re
from collections import Counter
from datetime import datetime
from pathlib import Path
from statistics import mean

N_FULL = 715
LABELS = ["support", "partial_support", "not_support", "contradicts"]


def base_model(set_name: str) -> str:
    """Registry name of a nugget set: drops the run suffixes ``.rN`` (replicate), ``.2call``, ``.repN`` and
    ``.planted`` (model names themselves contain dots, e.g. ``gemini-3.1-pro``)."""
    return re.sub(r"(\.(r\d+|2call|rep\d+|planted))+$", "", set_name)


def _jl(p: Path):
    return [json.loads(x) for x in p.read_text().splitlines() if x.strip()] if p.exists() else []


def _esc(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def _usd(x: float) -> str:
    return f"${x:,.2f}" if x >= 1 else f"${x:,.4f}"


# ------------------------------------------------------------------ extrapolation
def _fit(xs, ys):
    """OLS y = a + b x; a negative slope falls back to the mean (b = 0)."""
    mx, my = mean(xs), mean(ys)
    sxx = sum((x - mx) ** 2 for x in xs)
    b = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sxx if sxx else 0.0
    if b < 0:
        return my, 0.0
    return my - b * mx, b


def _full_cost(calls, price, xs_full, batch):
    xs = [c["qa_tokens"] for c in calls]
    ai, bi = _fit(xs, [c["usage"]["input"] for c in calls])
    ao, bo = _fit(xs, [c["usage"]["output"] for c in calls])
    tin = sum(c["usage"]["input"] for c in calls)
    cache_frac = sum(c["usage"]["cached_input"] for c in calls) / tin if tin else 0
    pin, pout = price["usd_per_million_input"], price["usd_per_million_output"]
    pc = price.get("usd_per_million_cached_input", pin)
    tot_in = sum(ai + bi * x for x in xs_full)
    tot_out = sum(max(ao + bo * x, 0) for x in xs_full)
    usd = (tot_in * (1 - cache_frac) * pin + tot_in * cache_frac * pc + tot_out * pout) / 1e6
    if batch:
        usd *= 1 - price.get("batch_discount", 0)
    return usd, tot_in, tot_out, cache_frac


def extrapolate(calls, price, xs_full, batch=False, reps=1000):
    """Cost of running this call shape on every question of ``xs_full``, with a bootstrap 90 % CI."""
    point = _full_cost(calls, price, xs_full, batch)
    rng = random.Random(13)
    boots = []
    for _ in range(reps):
        s = [rng.choice(calls) for _ in calls]
        if len({c["qa_tokens"] for c in s}) < 2:
            continue
        boots.append(_full_cost(s, price, xs_full, batch)[0])
    boots.sort()
    lo, hi = boots[int(0.05 * len(boots))], boots[int(0.95 * len(boots)) - 1]
    return {"usd": point[0], "lo": lo, "hi": hi, "input_tokens": point[1], "output_tokens": point[2],
            "cache_frac": point[3]}


# ------------------------------------------------------------------ report
def build(out: Path, sample: list[dict], registry: dict, all_qs: list[dict]) -> Path:
    xs_full = [q["qa_tokens"] for q in all_qs]
    # the planted-error set (synthetic damage) and the 2-call set (same texts as its source) are left to
    # report_pilot.md
    creators = sorted(p.name for p in (out / "create").iterdir() if not p.name.endswith((".planted", ".2call")))
    nug = {m: _jl(out / "create" / m / "nuggets.jsonl") for m in creators}
    ccalls = {m: _jl(out / "create" / m / "calls.jsonl") for m in creators}
    val = {m: json.loads((out / "create" / m / "validation.json").read_text()) for m in creators}
    judges = sorted(p.name for p in (out / "selfscore").iterdir()) if (out / "selfscore").exists() else []
    ss, jcalls = {}, {}
    for j in judges:
        for d in sorted((out / "selfscore" / j).iterdir()):
            ss[(j, d.name)] = {a["nugget_id"]: a for a in _jl(d / "assignments.jsonl")}
            jcalls.setdefault(j, []).extend(_jl(d / "calls.jsonl"))
    L = []
    w = L.append
    w(f"# Nuggetization — `{out.name}`, {len(sample)} questions\n")
    w(f"Generated by `scripts/nuggets/nuggets.py report` on {datetime.now():%Y-%m-%d %H:%M}. "
      "Plan: `docs/20261011_224049_gold_answer_nuggetization_plan_v2.md`.\n")

    pr = []
    for m in creators:
        mf = out / "create" / m / "manifest.json"
        if mf.exists():
            j = json.loads(mf.read_text())
            p_ = j.get("prompt") or (f"{j['source']} repaired with {j['repair_prompt']}" if "repair_prompt" in j else "?")
            pr.append(f"{m}: `{p_}`")
        else:
            pr.append(f"{m}: ?")
    for (j, s_) in ss:
        mf = out / "selfscore" / j / s_ / "manifest.json"
        pj = json.loads(mf.read_text())["prompt"] if mf.exists() else "scripts/nuggets/prompts/assign_v1.pt.md (no manifest)"
        pr.append(f"{j} on {s_}: `{pj}`")
    w("**Prompts:** creation — " + "; ".join(pr[:len(creators)]) + ". Judges — " + "; ".join(pr[len(creators):]) + ".\n")

    # sample
    w("## 1. Sample\n")
    w("`preview_10` = one question per answer-length decile (o200k tokens of question + answer, seed 13); "
      "it is the first pick of each decile of `stratified_30`, so the pilot will reuse these 10.\n")
    w("| Q | Summary | q+a tokens | Verdict | Enum. | R$ | % |\n|---|---|---:|:-:|:-:|:-:|:-:|")
    import re
    for q in sample:
        a = q["answer_cleaned"]
        w(f"| {q['question_number']} | {_esc(q['question_summary'][:45])} | {q['qa_tokens']} | "
          f"{'✓' if re.match(r'\s*(Sim|Não)\b', a) else ''} | "
          f"{'✓' if re.search(r'(?m)^\s*(\d{1,2}|[a-z])\s*[-–)]\s', a) else ''} | "
          f"{'✓' if 'R$' in a else ''} | {'✓' if '%' in a else ''} |")
    tot_s = sum(q["qa_tokens"] for q in sample)
    w(f"\nSample: {tot_s:,} q+a tokens (mean {tot_s / len(sample):.0f}); all 715: {sum(xs_full):,} "
      f"(mean {sum(xs_full) / len(xs_full):.0f}).\n")

    # creators
    w("## 2. Nugget sets\n")
    w("| Creator | Served model | Nuggets | Per q (min–max) | Vital | Errors | Warnings | Char coverage | Retries |")
    w("|---|---|---:|---|---:|---:|---:|---:|---:|")
    for m in creators:
        ns, cs = nug[m], ccalls[m]
        per = Counter(n["question_number"] for n in ns)
        cov = mean(r["char_coverage"] for r in val[m]["questions"])
        w(f"| {m} | {cs[0]['served'] if cs else '—'} | {len(ns)} | {len(ns) / len(sample):.1f} ({min(per.values())}–{max(per.values())}) | "
          f"{sum(n['importance'] == 'vital' for n in ns) / len(ns):.0%} | {val[m]['totals']['errors']} | "
          f"{val[m]['totals']['warnings']} | {cov:.0%} | {sum(c.get('attempts', 1) - 1 for c in cs)} |")
    w("\n**Categories**\n")
    cats = ["resposta_direta", "regra", "condicao", "valor_prazo", "procedimento_pgd", "definicao"]
    w("| Creator | " + " | ".join(cats) + " |\n|---|" + "---:|" * len(cats))
    for m in creators:
        c = Counter(n["category"] for n in nug[m])
        w(f"| {m} | " + " | ".join(str(c.get(k, 0)) for k in cats) + " |")
    w("\n**Nuggets per question**\n")
    w("| Q | q+a tokens | " + " | ".join(creators) + " |\n|---|---:|" + "---:|" * len(creators))
    for q in sample:
        w(f"| {q['question_number']} | {q['qa_tokens']} | " + " | ".join(
            str(sum(n["question_number"] == q["question_number"] for n in nug[m])) for m in creators) + " |")
    w("\n**Validation issues by code**\n")
    codes = sorted({i["code"] for m in creators for r in val[m]["questions"] for i in r["errors"] + r["warnings"]})
    if codes:
        w("| Code | Severity | " + " | ".join(creators) + " |\n|---|---|" + "---:|" * len(creators))
        for code in codes:
            sev = "error" if any(i["code"] == code for m in creators for r in val[m]["questions"] for i in r["errors"]) else "warning"
            w(f"| `{code}` | {sev} | " + " | ".join(str(sum(i["code"] == code for r in val[m]["questions"]
                                                           for i in r["errors"] + r["warnings"])) for m in creators) + " |")

    # self-score
    if ss:
        w("\n## 3. Gold self-score (§3.5.5)\n")
        w("Each judge labels the nuggets against the **gold answer they came from**; everything should be `support`.\n")
        w("| Judge | Nugget set | Nuggets | " + " | ".join(LABELS) + " | support rate |\n|---|---|---:|" + "---:|" * (len(LABELS) + 1))
        for (j, s), a in ss.items():
            c = Counter(x["label"] for x in a.values())
            w(f"| {j} | {s} | {len(a)} | " + " | ".join(str(c.get(k, 0)) for k in LABELS) +
              f" | {c.get('support', 0) / max(len(a), 1):.1%} |")

    # tokens and cost
    w("\n## 4. Tokens and cost per call (measured, standard prices, synchronous)\n")
    w("| Role | Model | Calls | Input (mean) | Cached | Output incl. reasoning (mean / max) | Reasoning (mean) | $/call (mean) | Spent | Latency (mean s) |")
    w("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    spent = 0.0
    # cost rows: plain creation runs only (replicates included); 2-call and repaired sets have other call shapes
    groups = [("create", m, ccalls[m]) for m in creators
              if ccalls[m] and all(c["role"] == "create" for c in ccalls[m])] + [("judge", j, jcalls[j]) for j in jcalls]
    for role, m, cs in groups:
        fresh = [c for c in cs if not c["from_cache"]]
        s = sum(c["usd_standard"] for c in cs)
        spent += s
        w(f"| {role} | {m} | {len(cs)} | {mean(c['usage']['input'] for c in cs):,.0f} | "
          f"{mean(c['usage']['cached_input'] for c in cs):,.0f} | {mean(c['usage']['output'] for c in cs):,.0f} / "
          f"{max(c['usage']['output'] for c in cs):,} | {mean(c['usage']['reasoning'] for c in cs):,.0f} | "
          f"{_usd(s / len(cs))} | {_usd(s)} | {mean(c['latency_s'] for c in cs):.0f} |")
    ledger = out / "costs.csv"
    if ledger.exists():
        import csv
        rows = list(csv.DictReader(ledger.open()))
        led = sum(float(r["usd_standard"]) for r in rows)
        w(f"\nTotal of the accepted calls above: **{_usd(spent)}**. Ledger `costs.csv` (every API call, retries "
          f"and probes included): **{_usd(led)}** in {len(rows)} calls.\n")

    # extrapolation
    w("## 5. Extrapolation to all 715 questions\n")
    w("Input and output tokens are fitted per (role, model) as a linear function of the question + answer "
      f"length (o200k tokens) over the {len(sample)} calls, then summed over the 715 real lengths. The cached share of "
      f"input is the one measured here. 90 % interval: bootstrap over the {len(sample)} calls (1,000 resamples). "
      "Judge rows use the gold answer as the judged text; system answers will have other lengths.\n")
    w("| Role | Model | Input tokens | Output tokens | Standard | Batch | 90 % interval (as run) | Plan v2 assumption |")
    w("|---|---|---:|---:|---:|---:|---:|---|")
    plan = {("create", "gpt-6.1-sol"): "≈ $9 (Batch)", ("create", "gemini-3.1-pro"): "≈ $12 (Batch)",
            ("create", "qwen3.8-max"): "≈ $11–14", ("judge", "gemini-3.8-flash"): "≈ $3.5 / run (Batch)",
            ("judge", "gemini-3.1-pro"): "≈ $10 / run (Batch)", ("judge", "qwen3.8-max"): "≈ $11 / run",
            ("judge", "gpt-6.1-sol"): "≈ $9 / run (Batch)"}
    ext = {}
    for role, m, cs in groups:
        price = registry[base_model(m)]["price"]
        std = extrapolate(cs, price, xs_full, batch=False)
        bat = extrapolate(cs, price, xs_full, batch=True)
        ext[(role, m)] = (std, bat)
        has_batch = price.get("batch_discount", 0) > 0
        lo_hi = bat if has_batch else std
        w(f"| {role} | {m} | {std['input_tokens'] / 1e6:.2f}M | {std['output_tokens'] / 1e6:.2f}M | {_usd(std['usd'])} | "
          f"{_usd(bat['usd']) if has_batch else '—'} | {_usd(lo_hi['lo'])}–{_usd(lo_hi['hi'])} | {plan.get((role, m), '')} |")

    # phase 1-4 table
    def per_call(role, m, batch):
        e = ext.get((role, m))
        return None if e is None else e[1 if batch else 0]["usd"] / N_FULL

    def item(role, m, n_calls, batch, factor=1.0):
        pc = per_call(role, m, batch)
        return None if pc is None else pc * n_calls * factor

    rows = [
        ("OpenAI", "Pilot: 30 q × (1-call + 2-call mode + 2 prompt iterations + 2 same-model runs) = 180 creation calls, sync",
         item("create", "gpt-6.1-sol", 180, False), "≈ $5–7"),
        ("OpenAI", "Full creation, Batch", item("create", "gpt-6.1-sol", N_FULL, True), "≈ $9"),
        ("OpenAI", "Repair: 20 % of questions × 2 rounds = 286 creation-shaped calls, sync",
         item("create", "gpt-6.1-sol", 286, False), "≈ $3"),
        ("Gemini", "Pilot set on 30 q (3.1 Pro, sync) + pilot known-answer tests (≈ 120 Flash + 12 Pro judge calls, sync)",
         _sum(item("create", "gemini-3.1-pro", 30, False), item("judge", "gemini-3.8-flash", 120, False),
              item("judge", "gemini-3.1-pro", 12, False)), "≈ $2"),
        ("Gemini", "Second set, 3.1 Pro, Batch", item("create", "gemini-3.1-pro", N_FULL, True), "≈ $12"),
        ("Gemini", "Auditor 1, 3.1 Pro, Batch: 715 × 1.4 calls, judge-shaped × 1.3 (longer instructions)",
         item("judge", "gemini-3.1-pro", N_FULL * 1.4, True, 1.3), "≈ $16"),
        ("Gemini", "Alignment, round trip, corruption rewrites: ≈ 2,860 Flash calls, judge-shaped, Batch",
         item("judge", "gemini-3.8-flash", 2860, True), "≈ $5"),
        ("Gemini", "Known-answer tests: 3,000 Flash + 300 Pro judge calls, Batch",
         _sum(item("judge", "gemini-3.8-flash", 3000, True), item("judge", "gemini-3.1-pro", 300, True)), "≈ $18"),
        ("Alibaba", "Pilot set on 30 q", item("create", "qwen3.8-max", 30, False), "< $1"),
        ("Alibaba", "Third set (no batch)", item("create", "qwen3.8-max", N_FULL, False), "≈ $11–14"),
        ("Alibaba", "Auditor 2: 715 × 1.4 calls, judge-shaped × 1.3",
         item("judge", "qwen3.8-max", N_FULL * 1.4, False, 1.3), "≈ $15"),
        ("Alibaba", "Round-trip comparison: 715 judge-shaped calls", item("judge", "qwen3.8-max", N_FULL, False), "≈ $8–11"),
    ]
    w("\n## 6. Updated cost estimate, phases 1–4 (plan v2 §6.4)\n")
    w("Same call counts as the plan; per-call costs from §5. Roles not run in the preview (auditors, aligner, "
      "round trip, corruption rewrites) are priced as judge-shaped calls of the same model, which is the closest "
      "measured shape. The open-weight Qwen judge on the HF endpoint is not measured and keeps the plan's figure.\n")
    w("| Provider | Item | Preview-based | Plan v2 |\n|---|---|---:|---:|")
    subtot = {}
    for prov, desc, v, p in rows:
        w(f"| {prov} | {desc} | {_usd(v) if v is not None else 'n/a'} | {p} |")
        subtot[prov] = subtot.get(prov, 0) + (v or 0)
    for prov, v in subtot.items():
        w(f"| **{prov}** | **subtotal** | **{_usd(v)}** | |")
    w(f"| HF endpoint | Known-answer tests with the open-weight Qwen judge | $10–25 (not measured) | ≈ $10–25 |")
    tot = sum(subtot.values())
    if any(v is None for _, _, v, _ in rows):
        w("| | **Total, phases 1–4** | **incomplete: some roles not measured in this run (n/a rows)** | **≈ $115–140** |")
    else:
        w(f"| | **Total, phases 1–4** | **{_usd(tot + 10)}–{_usd(tot + 25)}** | **≈ $115–140** |")
    w("\n**Scoring (phase 5), per answer run of 715 questions and per nugget set:**\n")
    w("| Judge | Preview-based | Plan v2 |\n|---|---:|---:|")
    for j in jcalls:
        price = registry[base_model(j)]["price"]
        b = price.get("batch_discount", 0) > 0
        w(f"| {j}{', Batch' if b else ''} | {_usd(ext[('judge', j)][1 if b else 0]['usd'])} | {plan.get(('judge', j), '')} |")

    # per question
    w("\n## 7. Per-question detail\n")
    w("Issues: **E** = validator error, W = warning. Self-score columns: label given by each judge against the gold "
      "answer (S support, P partial, N not_support, C contradicts).\n")
    abbr = {"support": "S", "partial_support": "P", "not_support": "N", "contradicts": "C"}
    for q in sample:
        qn = q["question_number"]
        w(f"### Q{qn} — {q['question_summary']}\n")
        w(f"**Pergunta:** {q['question_text']}\n")
        w("<details><summary>Gold answer</summary>\n\n```text\n" + q["answer_cleaned"].strip() + "\n```\n</details>\n")
        for m in creators:
            ns = [n for n in nug[m] if n["question_number"] == qn]
            vq = next(r for r in val[m]["questions"] if r["question_number"] == qn)
            js = [j for (j, s) in ss if s == m]
            w(f"**{m}** — {len(ns)} nuggets, coverage {vq['char_coverage']:.0%}\n")
            w("| # | Imp. | Category | Nugget | Legal basis | Issues | " + " | ".join(js) + " |")
            w("|---|---|---|---|---|---|" + "---|" * len(js))
            for n in ns:
                iss = "; ".join(("**E** " if i["severity"] == "error" else "W ") + i["code"] +
                                (f" ({_esc(i['detail'])})" if i["detail"] else "") for i in n["issues"])
                lab = " | ".join(abbr.get(ss[(j, m)].get(n["nugget_id"], {}).get("label"), "") for j in js)
                w(f"| {n['ordinal']} | {n['importance']} | {n['category']} | {_esc(n['text'])} | "
                  f"{_esc('; '.join(n['legal_basis']))} | {iss} | {lab} |")
            qlevel = [i for i in vq["errors"] + vq["warnings"] if i["nugget_id"] is None]
            if qlevel:
                w("\nAnswer-level: " + "; ".join(f"{i['code']} ({_esc(i['detail'])})" for i in qlevel))
            notes = [(j, n["ordinal"], ss[(j, m)][n["nugget_id"]]) for j in js for n in ns
                     if ss[(j, m)].get(n["nugget_id"], {}).get("label") not in (None, "support")]
            if notes:
                w("\nJudge notes on non-`support` labels: " + " ".join(
                    f"[{j} #{o}: {a['label']} — {_esc(a['justification'])}]" for j, o, a in notes))
            w("")
    path = out / "report.md"
    path.write_text("\n".join(L) + "\n")
    return path


def _sum(*xs):
    return None if any(x is None for x in xs) else sum(xs)
