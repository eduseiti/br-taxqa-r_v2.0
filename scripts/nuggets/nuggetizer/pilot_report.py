"""Phase 1 pilot report: costs per role, same-model noise vs cross-family agreement, 1 vs 2 calls,
round trip, two-auditor review and repair, gold self-score and known-answer tests (plan v2 §4)."""
from __future__ import annotations

import csv
import json
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path
from statistics import mean

from . import report as rep
from llm_client.client import BATCH_DISCOUNT, BATCH_TAG

from .validate import locate, norm

CHECKS = ["c1_faithful", "c2_self_contained", "c3_one_unit", "c4_importance"]
MATCH = {"same", "a_broader", "b_broader", "overlap"}      # "conflict" and "none" are not a match
N_FULL = 715


def _jl(p: Path):
    return rep._jl(p)


def _pct(x, d=0):
    return "—" if x is None else f"{x:.{d}%}"


def _ratio(a, b):
    return a / b if b else None


def _align(out, a, b):
    """Alignment rows of the pair, in either direction, as {a_id: (b_ids, relation)} from A's side and
    the set of B ids matched."""
    p = out / "align" / f"{a}__{b}" / "alignment.jsonl"
    if p.exists():
        rows = _jl(p)
        return {r["a"]: (r["b"], r["relation"]) for r in rows}, {x for r in rows if r["relation"] in MATCH for x in r["b"]}
    return None, None


def build(out: Path, sample: list[dict], registry: dict, all_qs: list[dict], primary: str = "gpt-6.1-sol",
          others: tuple[str, str] = ("gemini-3.1-pro", "qwen3.8-max")) -> Path:
    qd = {q["question_number"]: q for q in sample}
    sets = sorted(p.name for p in (out / "create").iterdir())
    nug = {s: _jl(out / "create" / s / "nuggets.jsonl") for s in sets}
    val = {s: json.loads((out / "create" / s / "validation.json").read_text())
           for s in sets if (out / "create" / s / "validation.json").exists()}
    L = []
    w = L.append
    w(f"# Nuggetization phase 1 pilot — {len(sample)} questions (`stratified_30`)\n")
    w(f"Generated by `scripts/nuggets/nuggets.py pilotreport` on {datetime.now():%Y-%m-%d %H:%M}. "
      "Plan: `docs/20261011_224049_gold_answer_nuggetization_plan_v2.md` §4 phase 1. Nuggets side by side and "
      "the per-question detail: `report.md`.\n")

    # ------------------------------------------------------------ 1. costs
    rows = list(csv.DictReader((out / "costs.csv").open()))
    w("## 1. Cost ledger by role and model (every API call incl. retries)\n")
    w("Standard = synchronous price; billed = what the provider charges (Batch API rows at half price).\n")
    w("| Role | Model | Calls | Retries | Input (mean) | Output incl. reasoning (mean) | $/call (standard) | Standard | Billed |")
    w("|---|---|---:|---:|---:|---:|---:|---:|---:|")
    g = defaultdict(list)
    for r in rows:
        tag = r["tag"].removeprefix(BATCH_TAG)
        role = tag.split(":")[0]
        if role == "create" and tag.count(":") == 2:
            role = "create (replicate)"
        if r["tag"].startswith(BATCH_TAG):
            role += " (batch)"
        g[(role, r["model"])].append(r)

    def billed(rs):
        return sum(float(r["usd_standard"]) * ((1 - BATCH_DISCOUNT) if r["tag"].startswith(BATCH_TAG) else 1)
                   for r in rs)

    for (role, m), rs in sorted(g.items()):
        usd = sum(float(r["usd_standard"]) for r in rs)
        w(f"| {role} | {m} | {len(rs)} | {sum(r['attempt'] != '1' for r in rs)} | "
          f"{mean(int(r['input']) for r in rs):,.0f} | {mean(int(r['output']) for r in rs):,.0f} | "
          f"{rep._usd(usd / len(rs))} | {rep._usd(usd)} | {rep._usd(billed(rs))} |")
    tot = sum(float(r["usd_standard"]) for r in rows)
    w(f"| **all** | | **{len(rows)}** | | | | | **{rep._usd(tot)}** | **{rep._usd(billed(rows))}** |\n")

    # ------------------------------------------------------------ 2. sets
    w("## 2. Nugget sets\n")
    w("| Set | Nuggets | Per q (min–max) | Vital | Errors | Warnings | Char coverage |")
    w("|---|---:|---|---:|---:|---:|---:|")
    for s in sets:
        ns = nug[s]
        per = Counter(n["question_number"] for n in ns)
        v = val.get(s)
        cov = mean(r["char_coverage"] for r in v["questions"]) if v else None
        w(f"| {s} | {len(ns)} | {len(ns) / len(sample):.1f} ({min(per.values())}–{max(per.values())}) | "
          f"{_pct(sum(n['importance'] == 'vital' for n in ns) / len(ns))} | {v['totals']['errors'] if v else '—'} | "
          f"{v['totals']['warnings'] if v else '—'} | {_pct(cov)} |")
    codes = sorted({i["code"] for v in val.values() for r in v["questions"] for i in r["errors"] + r["warnings"]})
    if codes:
        w("\n| Validator code | " + " | ".join(val) + " |\n|---|" + "---:|" * len(val))
        for c in codes:
            w(f"| `{c}` | " + " | ".join(str(sum(i["code"] == c for r in v["questions"] for i in r["errors"] + r["warnings"]))
                                         for v in val.values()) + " |")
    w("\n**Nuggets per question** (primary, replicates, other families)\n")
    cols = [s for s in [primary, f"{primary}.r2", f"{primary}.r3", *others] if s in nug]
    w("| Q | q+a tokens | " + " | ".join(cols) + " |\n|---|---:|" + "---:|" * len(cols))
    for q in sample:
        w(f"| {q['question_number']} | {q['qa_tokens']} | " + " | ".join(
            str(sum(n["question_number"] == q["question_number"] for n in nug[s])) for s in cols) + " |")

    # ------------------------------------------------------------ 3. agreement
    w("\n## 3. Same-model noise vs cross-family agreement (§3.5.2, §3.5.4)\n")
    w("Alignment by `gemini-3.8-flash` (`align_v1`), one call per question and pair. A nugget of A is **matched** "
      "when the aligner relates it to some B nugget as `same`, `a_broader`, `b_broader` or `overlap`; `conflict` "
      "and `none` are not matches. \"Same\" counts only the `same` relation. Importance agreement is over "
      "`same` pairs whose B side is a single nugget.\n")
    w("| A | B | A nuggets | Matched in B | `same` | `conflict` | B nuggets matched by A | Importance agreement |")
    w("|---|---|---:|---:|---:|---:|---:|---:|")
    pairs = sorted(p.name.split("__") for p in (out / "align").iterdir()) if (out / "align").exists() else []
    nid = {s: {n["nugget_id"]: n for n in nug[s]} for s in nug}
    for a, b in pairs:
        al, bhit = _align(out, a, b)
        rel = Counter(r for _, r in al.values())
        same1 = [(x, bs[0]) for x, (bs, r) in al.items() if r == "same" and len(bs) == 1]
        agree = _ratio(sum(nid[a][x]["importance"] == nid[b][y]["importance"] for x, y in same1), len(same1))
        w(f"| {a} | {b} | {len(al)} | {_pct(_ratio(sum(r in MATCH for r in rel.elements()), len(al)))} | "
          f"{_pct(_ratio(rel['same'], len(al)))} | {rel['conflict']} | {_pct(_ratio(len(bhit), len(nug[b])))} | "
          f"{_pct(agree)} ({len(same1)}) |")

    # stability of the primary set
    a1, _ = _align(out, primary, others[0])
    a2, _ = _align(out, primary, others[1])
    if a1 and a2:
        w("\n**Cross-family stability of the primary nuggets** (how many families made a matching nugget, the "
          "primary included):\n")
        stab = {x: 1 + (a1[x][1] in MATCH) + (a2[x][1] in MATCH) for x in a1 if x in a2}
        by_cat = defaultdict(Counter)
        for x, k in stab.items():
            by_cat[nid[primary][x]["category"]][k] += 1
            by_cat["(all)"][k] += 1
            by_cat[f"(importance {nid[primary][x]['importance']})"][k] += 1
        strict = {x: 1 + (a1[x][1] == "same") + (a2[x][1] == "same") for x in a1 if x in a2}
        cs = Counter(strict.values())
        w(f"Strict variant (only the `same` relation counts): 3/3 {_pct(cs[3] / len(strict))}, 2/3 "
          f"{_pct(cs[2] / len(strict))}, 1/3 {_pct(cs[1] / len(strict))}.\n")
        w("| Group | Nuggets | 3/3 | 2/3 | 1/3 |\n|---|---:|---:|---:|---:|")
        for c in sorted(by_cat, key=lambda c: (not c.startswith("("), c)):
            n = sum(by_cat[c].values())
            w(f"| {c} | {n} | {_pct(by_cat[c][3] / n)} | {_pct(by_cat[c][2] / n)} | {_pct(by_cat[c][1] / n)} |")
        r2, _ = _align(out, primary, f"{primary}.r2")
        r3, _ = _align(out, primary, f"{primary}.r3")
        if r2 and r3:
            sm = {x: 1 + (r2[x][1] in MATCH) + (r3[x][1] in MATCH) for x in r2 if x in r3}
            c = Counter(sm.values())
            sms = Counter(1 + (r2[x][1] == "same") + (r3[x][1] == "same") for x in r2 if x in r3)
            w(f"\nFor comparison, **same-model stability** (primary vs its two replicates): 3/3 {_pct(c[3] / len(sm))}, "
              f"2/3 {_pct(c[2] / len(sm))}, 1/3 {_pct(c[1] / len(sm))} of {len(sm)} nuggets; strict: 3/3 "
              f"{_pct(sms[3] / len(sm))}.\n")
        # vital agreement across families
        vit = [x for x in stab if stab[x] == 3]
        agree3 = 0
        n3 = 0
        for x in vit:
            b1, b2 = a1[x][0], a2[x][0]
            if len(b1) == 1 and len(b2) == 1:
                n3 += 1
                agree3 += nid[primary][x]["importance"] == nid[others[0]][b1[0]]["importance"] == \
                    nid[others[1]][b2[0]]["importance"]
        w(f"Importance identical in all three families: {_pct(_ratio(agree3, n3))} of the {n3} 3/3 nuggets matched "
          "one-to-one in both other sets.\n")

        # span-overlap as a cheap aligner (plan: span first, LLM for the rest)
        tp = fp = fn = 0
        for (oth, al) in ((others[0], a1), (others[1], a2)):
            ob = defaultdict(list)
            for n in nug[oth]:
                ob[n["question_number"]].append(n)
            for x, (bs, r) in al.items():
                pa = nid[primary][x]
                ans = norm(qd[pa["question_number"]]["answer_cleaned"])
                ra = locate(pa["source_span"], ans)[1]
                for nb in ob[pa["question_number"]]:
                    rb = locate(nb["source_span"], ans)[1]
                    ov = sum(max(0, min(p[1], q[1]) - max(p[0], q[0])) for p in ra for q in rb)
                    short = min(sum(p[1] - p[0] for p in ra) or 1, sum(q[1] - q[0] for q in rb) or 1)
                    span_m = ov >= 0.5 * short
                    llm_m = r in MATCH and nb["nugget_id"] in bs
                    tp += span_m and llm_m
                    fp += span_m and not llm_m
                    fn += llm_m and not span_m
        w(f"**Span overlap as a cheap aligner** (≥ 50 % of the shorter span, primary vs each other family): it "
          f"agrees with the LLM aligner on {tp} pairs; it would add {fp} pairs the LLM did not match and miss {fn} "
          f"LLM matches (precision {_pct(_ratio(tp, tp + fp))}, recall {_pct(_ratio(tp, tp + fn))}).\n")

    # ------------------------------------------------------------ 4. 1 vs 2 calls
    two = f"{primary}.2call"
    if two in nug:
        w("## 4. One call vs two calls (importance in a second call)\n")
        w("The 2-call set keeps the texts of the primary set and asks `gpt-6.1-sol` for vital/okay in a second call "
          "(`importance_v1`). References: the importance given by the other two families to the same fact (3/3 "
          "nuggets matched one-to-one, both families agreeing) and by the replicates (same-model).\n")
        ns2 = {n["nugget_id"]: n for n in nug[two]}
        ch = [x for x in ns2 if ns2[x]["importance"] != ns2[x]["importance_1call"]]
        w(f"- Labels changed by the second call: **{len(ch)} of {len(ns2)}** ({_pct(len(ch) / len(ns2))}); "
          f"vital share 1-call {_pct(mean(n['importance_1call'] == 'vital' for n in ns2.values()))} → 2-call "
          f"{_pct(mean(n['importance'] == 'vital' for n in ns2.values()))}.")
        tr = Counter(f"{ns2[x]['importance_1call']} → {ns2[x]['importance']}" for x in ch)
        w("- Direction: " + ", ".join(f"{k}: {v}" for k, v in tr.items()) + ".")
        if a1 and a2:
            ref = {}
            for x in a1:
                if x in a2 and a1[x][1] == "same" and a2[x][1] == "same" and len(a1[x][0]) == 1 and len(a2[x][0]) == 1:
                    i1, i2 = nid[others[0]][a1[x][0][0]]["importance"], nid[others[1]][a2[x][0][0]]["importance"]
                    if i1 == i2:
                        ref[x] = i1
            one = _ratio(sum(ns2[x]["importance_1call"] == v for x, v in ref.items()), len(ref))
            twoc = _ratio(sum(ns2[x]["importance"] == v for x, v in ref.items()), len(ref))
            w(f"- Agreement with the other two families' common label ({len(ref)} nuggets): 1-call {_pct(one)}, "
              f"2-call {_pct(twoc)}.")
        r2, _ = _align(out, primary, f"{primary}.r2")
        r3, _ = _align(out, primary, f"{primary}.r3")
        if r2 and r3:
            agr = []
            for al, s in ((r2, f"{primary}.r2"), (r3, f"{primary}.r3")):
                for x, (bs, r) in al.items():
                    if r == "same" and len(bs) == 1:
                        agr.append(ns2[x]["importance_1call"] == nid[s][bs[0]]["importance"])
            w(f"- Same-model importance agreement (1-call primary vs 1-call replicates, `same` one-to-one pairs): "
              f"{_pct(_ratio(sum(agr), len(agr)))} of {len(agr)} — the noise floor of a single call.")
        w("")

    # ------------------------------------------------------------ 5. round trip
    if (out / "roundtrip").exists():
        w("## 5. Round trip (§3.5.4)\n")
        w("`gemini-3.8-flash` rewrote each answer from the primary nuggets alone (texts only, no `legal_basis`); "
          "`qwen3.8-max` listed gold statements missing from or altered in the rewrite.\n")
        w("| Run | Check prompt | Findings | Questions | missing / altered |\n|---|---|---:|---:|---|")
        for d in sorted((out / "roundtrip").iterdir()):
            miss = _jl(d / "missing.jsonl")
            mf = json.loads((d / "manifest.json").read_text())
            c = Counter(m["problem"] for m in miss)
            w(f"| `{d.name}` | `{mf['check_prompt']}` | {len(miss)} | {len({m['question_number'] for m in miss})} | "
              f"{c['missing']} / {c['altered']} |")
        w("")

    # ------------------------------------------------------------ 6. audit and repair
    if (out / "audit").exists():
        w("## 6. Two-auditor review and repair (§3.5.3)\n")
        w("Auditors: `gemini-3.1-pro` and `qwen3.8-max`, prompt `audit_v1` (checks C1–C6 of plan v1 §3.4.1), on the "
          "primary set. A nugget is **flagged** on a check when the auditor answers `false`.\n")
        for s in sorted(p.name for p in (out / "audit").iterdir()):
            auds = sorted(p.name for p in (out / "audit" / s).iterdir())
            if len(auds) < 2 or s.endswith(".planted"):
                continue
            A = {x: {r["nugget_id"]: r for r in _jl(out / "audit" / s / x / "nuggets.jsonl")} for x in auds}
            Q = {x: {r["question_number"]: r for r in _jl(out / "audit" / s / x / "questions.jsonl")} for x in auds}
            common = sorted(set(A[auds[0]]) & set(A[auds[1]]))
            w(f"**Set `{s}`** ({len(common)} nuggets audited by both, {len(Q[auds[0]])} questions)\n")
            w("| Check | " + " | ".join(auds) + " | Both | Both, 95 % CI over questions |\n|---|" + "---:|" * (len(auds) + 2))
            for k in CHECKS + ["any"]:
                def bad(x, n):
                    r = A[x][n]
                    return not all(r[c] for c in CHECKS) if k == "any" else not r[k]
                both = [n for n in common if bad(auds[0], n) and bad(auds[1], n)]
                ci = _boot_ci(common, set(both))
                w(f"| {k} | " + " | ".join(_pct(_ratio(sum(bad(x, n) for n in common), len(common)), 1) for x in auds) +
                  f" | {len(both)} ({_pct(_ratio(len(both), len(common)), 1)}) | {ci} |")
            om = {x: sum(len(r["omissions"]) for r in Q[x].values()) for x in auds}
            rd = {x: sum(len(r["redundant"]) for r in Q[x].values()) for x in auds}
            w(f"\nOmissions (C5): " + ", ".join(f"{x} {om[x]}" for x in auds) +
              ". Redundant pairs (C6): " + ", ".join(f"{x} {rd[x]}" for x in auds) + ".\n")
        for s in sets:
            mf = out / "create" / s / "manifest.json"
            if mf.exists() and json.loads(mf.read_text()).get("mode") == "repair":
                m = json.loads(mf.read_text())
                calls = _jl(out / "create" / s / "calls.jsonl")
                w(f"**Repair `{m['source']}` → `{s}`:** {len(m['repaired'])} questions sent back to the creator "
                  f"({', '.join(m['repaired'])}), {sum(len(c['issues']) for c in calls)} agreed issues; "
                  f"{len(nug[m['source']])} → {len(nug[s])} nuggets.\n")

        for s in sorted(p.name for p in (out / "audit").iterdir() if p.name.endswith(".planted")):
            pl = {x["nugget_id"]: x for x in _jl(out / "create" / s / "planted.jsonl")}
            w(f"**Auditor sensitivity on planted errors** (set `{s}`, one damaged nugget per question; "
              f"types: {', '.join(f'{k} {v}' for k, v in sorted(Counter(x['type'] for x in pl.values()).items()))})\n")
            w("| Auditor | Planted errors flagged | On the expected check | Other nuggets flagged |\n|---|---:|---:|---:|")
            flagged = {}
            for x in sorted(p.name for p in (out / "audit" / s).iterdir()):
                A = {r["nugget_id"]: r for r in _jl(out / "audit" / s / x / "nuggets.jsonl")}
                hit = {n for n in pl if n in A and not all(A[n][c] for c in CHECKS)}
                exp = sum(n in A and not A[n][pl[n]["expected_check"]] for n in pl)
                other = [n for n in A if n not in pl]
                fo = sum(not all(A[n][c] for c in CHECKS) for n in other)
                flagged[x] = hit
                w(f"| {x} | {len(hit)}/{len(pl)} | {exp}/{len(pl)} | {fo}/{len(other)} ({_pct(_ratio(fo, len(other)), 1)}) |")
            if len(flagged) == 2:
                f1, f2 = flagged.values()
                w(f"| **both** | {len(f1 & f2)}/{len(pl)} | | |")
            miss = {}
            for x, hit in flagged.items():
                for n in pl:
                    if n not in hit:
                        miss.setdefault(n, []).append(x)
            if miss:
                w("\nMissed: " + "; ".join(f"{n} ({pl[n]['type']}: {pl[n]['detail']}) by {', '.join(v)}" for n, v in miss.items()))
            w("")

    # ------------------------------------------------------------ 7. self-score
    if (out / "selfscore").exists():
        w("## 7. Gold self-score (§3.5.5, `assign_v2`)\n")
        w("| Judge | Nugget set | Nuggets | support | partial | not_support | contradicts | Support rate |")
        w("|---|---|---:|---:|---:|---:|---:|---:|")
        for j in sorted(p.name for p in (out / "selfscore").iterdir()):
            for d in sorted((out / "selfscore" / j).iterdir()):
                a = _jl(d / "assignments.jsonl")
                c = Counter(x["label"] for x in a)
                w(f"| {j} | {d.name} | {len(a)} | {c['support']} | {c['partial_support']} | {c['not_support']} | "
                  f"{c['contradicts']} | {_pct(c['support'] / len(a), 1)} |")
        w("")

    # ------------------------------------------------------------ 8. known-answer tests
    if (out / "known").exists():
        w("## 8. Known-answer tests (§5.7, `assign_v2`)\n")
        w("Detection = target nugget not labelled `support`; specificity = non-target nuggets still `support` "
          "(nuggets whose expected label is ambiguous are left out). W and E: every nugget is a target. "
          "V_strict = mean share of vital nuggets labelled `support`.\n")
        for s in sorted(p.name for p in (out / "known").iterdir()):
            tests = _jl(out / "known" / s / "tests.jsonl")
            judges = sorted(p.name for p in (out / "known" / s).iterdir() if p.is_dir())
            w(f"**Set `{s}`:** {len(tests)} tests " + "(" + ", ".join(f"{k} {v}" for k, v in
                                                                   sorted(Counter(t['type'] for t in tests).items())) + ")\n")
            if not judges:
                continue
            mets = {j: json.loads((out / "known" / s / j / "metrics.json").read_text()) for j in judges
                    if (out / "known" / s / j / "metrics.json").exists()}
            w("| Type | " + " | ".join(f"{j}: detection (contradicts) | {j}: specificity | {j}: V_strict" for j in mets) +
              " |\n|---|" + "---:|---:|---:|" * len(mets))
            for t in ["G", "V", "Y", "N", "D", "C", "W", "E"]:
                cells = []
                for j, m in mets.items():
                    x = m.get(t)
                    if not x:
                        cells += ["—", "—", "—"]
                        continue
                    det = "—" if x["sensitivity"] is None else (
                        f"{_pct(x['sensitivity'])} ({_pct(x['contradicts_rate'])})" if t in "VYN" else _pct(x["sensitivity"]))
                    cells += [det + f" [{x['targets']}]", _pct(x["specificity"]), _pct(x["v_strict"])]
                w(f"| {t} | " + " | ".join(cells) + " |")
            for j in mets:
                mf = json.loads((out / "known" / s / j / "manifest.json").read_text())
                if mf.get("missing_tests"):
                    w(f"\n{j}: **partial**, {len(mf['missing_tests'])} tests not judged (daily quota): "
                      f"{', '.join(mf['missing_tests'])}.")
            for j, m in mets.items():
                p = m["_pooled"]
                w(f"\n{j}: pooled sensitivity {_pct(p['sensitivity'], 1)}, specificity {_pct(p['specificity'], 1)}, "
                  f"**balanced accuracy {_pct(p['balanced_accuracy'], 1)}**; `contradicts` precision "
                  f"{_pct(p['contradicts_precision'])} of {p['contradicts_labels']} labels.")
            w("")

    # ------------------------------------------------------------ 9. extrapolation
    w("## 9. Per-call cost of each role, extrapolated to 715 questions\n")
    w("Fitted per (role, model) on question + answer length, as in `report.md` §5. Known-answer and audit calls use "
      "gold-length answers. Batch = 50 % off where the provider offers it (not Qwen in Singapore).\n")
    w("| Role | Model | Calls | Standard, 715 calls | Batch, 715 calls |\n|---|---|---:|---:|---:|")
    xs_full = [q["qa_tokens"] for q in all_qs]
    groups = defaultdict(list)
    for base in ("create", "selfscore", "align", "roundtrip", "audit", "known"):
        root = out / base
        if not root.exists():
            continue
        for f in root.rglob("calls.jsonl"):
            for c in _jl(f):
                groups[(c["role"], c["model"])].append(c)
    for (role, m), cs in sorted(groups.items()):
        cs = [c for c in cs if not c.get("from_cache")] or cs
        if len({c["qa_tokens"] for c in cs}) < 2:
            continue
        price = registry[m]["price"]
        std = rep.extrapolate(cs, price, xs_full, batch=False, reps=200)
        bat = rep.extrapolate(cs, price, xs_full, batch=True, reps=200) if price.get("batch_discount") else None
        w(f"| {role} | {m} | {len(cs)} | {rep._usd(std['usd'])} | {rep._usd(bat['usd']) if bat else '—'} |")

    path = out / "report_pilot.md"
    path.write_text("\n".join(L) + "\n")
    return path


def _boot_ci(ids, flagged, reps=2000):
    """95 % CI of the flagged share, resampling questions (nuggets of a question move together)."""
    import random
    byq = defaultdict(list)
    for n in ids:
        byq[n.split("_")[0]].append(n in flagged)
    qs = list(byq)
    rng = random.Random(13)
    vals = []
    for _ in range(reps):
        s = [rng.choice(qs) for _ in qs]
        tot = sum(len(byq[q]) for q in s)
        vals.append(sum(sum(byq[q]) for q in s) / tot if tot else 0)
    vals.sort()
    return f"{vals[int(0.025 * reps)]:.1%}–{vals[int(0.975 * reps) - 1]:.1%}"
